#!/usr/bin/env python3
"""Per-tuple ground-truth builder for the cars dataset (2026-11-20).

User ruling: the official per-query GT files in ground_truth/ (verbatim
copies of files/cars/raw_results/ground_truth/, the no-suffix sf_19672
officials) are user assets and are NEVER regenerated by this script --
only hash-verified. What it (re)generates is solely the tuple-level
rowsets the engine layer needs on top of them:

  aggregate queries -- official GT is scalar/group, no rowset exists:
    Q4__tuple.csv  component_class == "ENGINE"              -> AVG input
    Q5__tuple.csv  Automatic & image-abnormal & audio-abnormal
  UCQ branches -- each branch runs as a standalone engine query
  (engine-name keyed, same names as workloads/scenarios/cars/q6.py
  / q7.py branch dicts):
    Q7__img / Q7__aud / Q7__txt   (dented / worn_out_brakes /
                                   ELECTRICAL SYSTEM)
    Q6__img_dmg / Q6__aud_dmg / Q6__fire  +  Q6__img_face /
    Q6__aud_face / Q6__txt_face   (Q6 = modalities DISAGREE: >=2
    modalities available, one judges damaged, another judges normal;
    "on fire" is the text modality's damaged-verdict per the official
    NL, not an extra AND. The ok side is DERIVED at assembly as
    face - dmg -- user order 2026-11-21, mirroring the official
    gold's three-judgment-then-derive shape; the retired 11-18
    materialized ok files live in data/cars/archived/)

It also RESTORES the two bare names a later 11-18 batch had repurposed
as census rowsets back to their official content:
    Q4.csv <- official scalar   Q5.csv <- official group table
(the displaced rowsets and the now-redundant Q4_answer.csv /
Q5_answer.csv copies are moved to data/cars/archived/, nothing deleted).

Sources: files/cars/data/sf_19672/car_data_denormalized.csv -- the
join-checked one-row-per-car table carrying the judgment labels the
engine never sees; GT derives from it or the answers would leak.
Formulas are the _phase0_cars_19672 census (9/9 parity certified
2026-11-18). Deterministic, no LLM, no run outputs. Idempotent.

Self-checks against the UNTOUCHED officials (exit 1 on mismatch):
    census Q1/Q2/Q3/Q6/Q7/Q8/Q9 == official rowsets
      (Q2 disclosed divergence: official EMPTY vs 1 label-noise car
       98676 -- official wins, informational)
    mean(2026 - year | Q4__tuple) == Q4.csv scalar
    len(Q5__tuple)               == Q5.csv Automatic count
    union(Q7 branches)           == Q7.csv car_id set
    Q6 branch composition        == Q6.csv car_id set (1906)
    data_full.csv holds NATIVE columns only (no derived features --
    iron rule 2026-11-19; the 11-18 n_avail column was removed 11-20
    by user order)

Usage: python3 data/cars/build_gt.py
"""
from __future__ import annotations

import hashlib
import shutil
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
GT = HERE / "ground_truth"
ARCHIVE = HERE / "archived"
OFFICIAL = HERE.parents[1] / "files/cars/raw_results/ground_truth"
DENORM = HERE.parents[1] / "files/cars/data/sf_19672/car_data_denormalized.csv"

# ---------------------------------------------------------------- sources
d = pd.read_csv(
    DENORM, dtype={"car_id": str, "vin": str, "complaint_id": str,
                   "image_id": str, "audio_id": str},
)

# ----------------------------------------------------------------- masks
dsm = d.damage_status.fillna("")
dp = d.detailed_problem.fillna("")
dp_abn = d.detailed_problem.notna() & ~dp.str.startswith("normal")
img_abn = d.damage_status.notna() & (d.damage_status != "no_damage")
# fire_* is Q6's text-damaged verdict ONLY: the official query scopes
# the text modality's "damaged" judgment to fire entailment ("For this
# query, for complaints, check if the car was on fire" + gold AI.IF);
# other queries use their own text labels (Q1 crash, Q4 component_class).
fire_abn = d.fire == True  # noqa: E712
img_ok = d.damage_status == "no_damage"
aud_ok = d.detailed_problem.notna() & dp.str.startswith("normal")
fire_ok = d.fire == False  # noqa: E712
n_avail = (d.damage_status.notna().astype(int)
           + d.detailed_problem.notna().astype(int)
           + d.fire.notna().astype(int))

FORMULAS = {
    "Q1": d[d.crash == True].car_id,                                   # noqa: E712
    "Q2": d[(d.fuel_type == "Electric")
            & (d.detailed_problem == "dead_battery")].car_id.unique(),
    "Q3": d[(d.transmission == "Manual")
            & (d.damage_status == "no_damage")].vin.dropna().unique(),
    "Q4": d[d.component_class == "ENGINE"].car_id.unique(),  # AVG input
    "Q5": d[(d.transmission == "Automatic") & img_abn & dp_abn].car_id.unique(),
    "Q6": d[(img_abn | dp_abn | fire_abn) & (img_ok | aud_ok | fire_ok)
            & (n_avail >= 2)].car_id.unique(),
    "Q7": d[(dp_abn & dp.str.contains("brake", case=False))
            | (d.component_class == "ELECTRICAL SYSTEM")
            | dsm.str.contains("dented")].car_id.unique(),
    "Q8": d[dsm.str.contains("puncture", case=False)
            & dsm.str.contains("scratch", case=False)].car_id.unique(),
    "Q9": d[dsm.str.contains("torn")
            & (d.detailed_problem == "bad_ignition")].car_id.unique(),
}
BRANCHES = {
    "Q7__img": d[dsm.str.contains("dented")].car_id.unique(),
    "Q7__aud": d[d.detailed_problem == "worn_out_brakes"].car_id.unique(),
    "Q7__txt": d[d.component_class == "ELECTRICAL SYSTEM"].car_id.unique(),
}

# Q6 branches (user order 2026-11-21): 3 dmg rowsets + 3 structural
# faces; the ok side is DERIVED at assembly (face - dmg), mirroring the
# official gold's three-judgment-then-derive shape. Each rowset sits
# inside its branch's DNF Sigma face (own modality available AND >=2
# of 3).
ge2 = n_avail >= 2
img_avail = d.damage_status.notna()
aud_avail = d.detailed_problem.notna()
txt_avail = d.fire.notna()
Q6_BRANCHES = {
    "Q6__img_dmg": d[img_abn & ge2].car_id.unique(),
    "Q6__aud_dmg": d[dp_abn & ge2].car_id.unique(),
    "Q6__fire": d[fire_abn & ge2].car_id.unique(),
    "Q6__img_face": d[img_avail & ge2].car_id.unique(),
    "Q6__aud_face": d[aud_avail & ge2].car_id.unique(),
    "Q6__txt_face": d[txt_avail & ge2].car_id.unique(),
}

# engine-branch rowsets (UCQ per-branch) + agg per-tuple sets
SETS = {**BRANCHES, **Q6_BRANCHES,
        "Q4__tuple": FORMULAS["Q4"], "Q5__tuple": FORMULAS["Q5"]}
OFFICIAL_NAMES = {f"Q{i}.csv" for i in range(1, 11)}
assert not OFFICIAL_NAMES & {f"{n}.csv" for n in SETS}, "official-file collision"

fails = 0

# ------------------------------------------- census parity vs officials
print(f"universe rows: {len(d)}")
for q in ["Q1", "Q2", "Q3", "Q5", "Q6", "Q7", "Q8", "Q9"]:
    official = pd.read_csv(OFFICIAL / f"{q}.csv", dtype=str)
    if q == "Q5":  # group-by count table
        off = int(official.loc[official.transmission == "Automatic",
                               "count"].iloc[0])
        ok = off == len(FORMULAS["Q5"])
        print(f"Q5  : official count {off} | census {len(FORMULAS['Q5'])} | "
              f"{'EQUAL' if ok else 'DIFF'}")
    else:
        col = "vin" if q == "Q3" else "car_id"
        so, sm = set(official[col].dropna()), set(FORMULAS[q])
        ok = so == sm
        tag = "EQUAL" if ok else "DIFF"
        # Known divergence (disclosed): official Q2 is EMPTY at sf_19672;
        # the census finds exactly car 98676, whose complaint text is
        # about daytime-running lights but carries a dead_battery label
        # (source label noise). Official GT wins -- informational.
        if q == "Q2" and not ok and not so and len(sm) == 1:
            tag = "DIFF (disclosed: official-empty vs 1 label-noise car)"
            ok = True
        print(f"{q:3}: official {len(so)} | census {len(sm)} | {tag} | "
              f"off-only {len(so - sm)} census-only {len(sm - so)}")
    fails += not ok

# Q4 scalar: AVG(2026 - year | component_class == ENGINE)
mine4 = (2026 - d[d.component_class == "ENGINE"].year.astype(float)).mean()
off4 = float(pd.read_csv(OFFICIAL / "Q4.csv")["average_age"].iloc[0])
ok4 = abs(mine4 - off4) < 1e-9
print(f"Q4  : official {off4!r} | census {mine4!r} | "
      f"{'EQUAL' if ok4 else 'DIFF'} (n={len(FORMULAS['Q4'])})")
fails += not ok4

# Q7 branch union consistency
union7 = set().union(*BRANCHES.values())
ok7 = union7 == set(FORMULAS["Q7"])
print(f"Q7 branches: img={len(BRANCHES['Q7__img'])} "
      f"aud={len(BRANCHES['Q7__aud'])} txt={len(BRANCHES['Q7__txt'])} | "
      f"union {len(union7)} vs census {len(set(FORMULAS['Q7']))} | "
      f"{'CONSISTENT' if ok7 else 'INCONSISTENT'}")
fails += not ok7

# Q6 branch composition == official disagreement answer (ok derived)
dmg_union = set(Q6_BRANCHES["Q6__img_dmg"]) | set(Q6_BRANCHES["Q6__aud_dmg"]) \
    | set(Q6_BRANCHES["Q6__fire"])
ok_union = (set(Q6_BRANCHES["Q6__img_face"]) - set(Q6_BRANCHES["Q6__img_dmg"])) \
    | (set(Q6_BRANCHES["Q6__aud_face"]) - set(Q6_BRANCHES["Q6__aud_dmg"])) \
    | (set(Q6_BRANCHES["Q6__txt_face"]) - set(Q6_BRANCHES["Q6__fire"]))
comp6 = dmg_union & ok_union
ok6 = comp6 == set(FORMULAS["Q6"]) == \
    set(pd.read_csv(OFFICIAL / "Q6.csv", dtype=str).car_id)
print(f"Q6 branches: dmg={len(dmg_union)} ok(derived)={len(ok_union)} | "
      f"composition {len(comp6)} vs census {len(set(FORMULAS['Q6']))} | "
      f"{'CONSISTENT' if ok6 else 'INCONSISTENT'}")
fails += not ok6

# base-table purity: NATIVE columns only (iron rule 2026-11-19)
base_cols = pd.read_csv(HERE / "data_full.csv", nrows=0).columns.tolist()
ok_pure = "n_avail" not in base_cols
print(f"{'EQUAL' if ok_pure else 'DIFF '} data_full.csv native-only "
      f"(no n_avail): columns={base_cols}")
fails += not ok_pure

# ------------------------------------- hash-verify existing verbatim copies
def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


for name in ["Q1", "Q2", "Q3", "Q6", "Q7", "Q8", "Q9", "Q10"]:
    mine, official = GT / f"{name}.csv", OFFICIAL / f"{name}.csv"
    ok = mine.exists() and sha(mine) == sha(official)
    print(f"{'SAME ' if ok else 'DIFF '} {name}.csv == official "
          f"({sha(official)[:12]})")
    fails += not ok

# -------------------------------------------------- write constructed sets
for name, mine in SETS.items():
    pd.DataFrame({"car_id": sorted(mine)}).to_csv(
        GT / f"{name}.csv", index=False)

# displaced ok-side branch files (2026-11-21 re-encoding: ok is
# derived as face - dmg and no longer generated) -- archive, never
# delete
for legacy in ("Q6__img_ok", "Q6__aud_ok", "Q6__nofire"):
    legacy_path = GT / f"{legacy}.csv"
    if legacy_path.exists():
        shutil.move(str(legacy_path), ARCHIVE / f"{legacy}.csv")
        print(f"ARCHIVED {legacy}.csv (ok side now derived: face - dmg)")

# -------------------------------------- restore repurposed bare Q4/Q5 names
ARCHIVE.mkdir(exist_ok=True)
for name, answer in [("Q4", "Q4_answer"), ("Q5", "Q5_answer")]:
    official, dst = OFFICIAL / f"{name}.csv", GT / f"{name}.csv"
    if not dst.exists() or sha(dst) != sha(official):
        # displaced census rowset (11-18 batch) -- archive, never delete
        if dst.exists():
            shutil.move(str(dst), ARCHIVE / f"{name}.rowset-displaced.csv")
        shutil.copy(official, dst)
        print(f"RESTORED {name}.csv <- official (displaced rowset archived)")
    ans = GT / f"{answer}.csv"
    if ans.exists():  # redundant copy of the official aggregate now
        shutil.move(str(ans), ARCHIVE / f"{answer}.csv")
        print(f"ARCHIVED {answer}.csv (== restored {name}.csv)")

print(f"RESULT: {'ALL SELF-CHECKS EQUAL' if fails == 0 else f'{fails} FAILURES'}")
sys.exit(1 if fails else 0)
