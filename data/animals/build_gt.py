#!/usr/bin/env python3
"""Per-tuple ground-truth builder for the animals dataset (2026-11-20).

User ruling: the official per-query GT files Q1-Q10.csv in ground_truth/
(byte-copies of files/animals/raw_results/ground_truth) are user assets
and are NEVER regenerated by this script -- only hash-verified. What it
(re)generates is solely the tuple-level rowsets the engine layer labels
against (census from the sf_200 native labels, the table the engine
never sees):

    standalone filters:  zebra_img / elephant_aud / monkey_img /
                         monkey_aud / impala_img
    either-modality unions (answer rowset + per-branch splits by
    media_id prefix img_/aud_):
        elephant_any + elephant_any__img / elephant_any__aud
        monkey_any   + monkey_any__img   / monkey_any__aud

Census (ported from revision/exp/R1.D3.1/2-batch-run/_build_universes.py
+ the 11-18 impala addition): data_full.csv is order-joined 1:1 with
files/animals/source_data/sf_200/image_data.csv.Species (image rows) and
audio_data.csv.Animal (audio rows); membership = token match over the
comma-separated label cell, case-insensitive. The positional join is
guarded by path-level alignment asserts (a same-(City, StationID) row
swap passes every official anchor while corrupting per-tuple GT --
proven by injection 2026-11-21).

Self-checks against the UNTOUCHED officials (exit 1 on mismatch):
    Q1/Q2 counts, Q3/Q4 argmax cities, Q5 union cities, Q6 anti cities
    (monkey-img minus monkey-aud), Q7 zebra-and-impala co-occur cities,
    Q8/Q9 intersect cities, Q10 argmax (City, StationID) pairs
    census rowsets == current GT files (regenerate a constructed file
    only on drift); Q1-Q10.csv engine copies == officials byte-wise

Usage: python3 data/animals/build_gt.py
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
GT = HERE / "ground_truth"
OFFICIAL = HERE.parents[1] / "files/animals/raw_results/ground_truth"
SF200 = HERE.parents[1] / "files/animals/source_data/sf_200"

fails = 0

# ------------------------------------------------------------- officials
for i in range(1, 11):
    mine, official = GT / f"Q{i}.csv", OFFICIAL / f"Q{i}.csv"
    ok = mine.exists() and hashlib.sha256(mine.read_bytes()).hexdigest() \
        == hashlib.sha256(official.read_bytes()).hexdigest()
    print(f"{'SAME ' if ok else 'DIFF '} Q{i}.csv == official")
    fails += not ok

# ----------------------------------------------------------------- census
ani = pd.read_csv(HERE / "data_full.csv", dtype=str, keep_default_na=False)
img_mask, aud_mask = ani.media_type == "image", ani.media_type == "audio"
img_sf = pd.read_csv(SF200 / "image_data.csv")
aud_sf = pd.read_csv(SF200 / "audio_data.csv")
img_labels = img_sf.Species.tolist()
aud_labels = aud_sf.Animal.tolist()


def remap(p) -> str:
    return str(p).replace("/home/jiale/SemBench/", "")


assert len(img_labels) == int(img_mask.sum()), "image label order-join size"
assert len(aud_labels) == int(aud_mask.sum()), "audio label order-join size"
# Path-level alignment: the positional label join is only sound if each
# row's media path equals its sf_200 source cell. Size checks alone were
# a proven blind spot (2026-11-21): a same-(City, StationID) row swap
# passes every official anchor while corrupting the per-tuple GT.
assert ani.loc[img_mask, "image_path"].tolist() \
    == [remap(p) for p in img_sf.ImagePath], "image path order-join"
assert ani.loc[aud_mask, "audio_path"].tolist() \
    == [remap(p) for p in aud_sf.AudioPath], "audio path order-join"
ani["label_species"] = ""
ani.loc[img_mask, "label_species"] = img_labels
ani.loc[aud_mask, "label_species"] = aud_labels


def has_species(mask: pd.Series, name: str) -> pd.Series:
    return mask & ani.label_species.map(
        lambda labels: name.upper()
        in [tok.strip().upper() for tok in str(labels).split(",")]
    )


def ids(mask: pd.Series) -> list[str]:
    return sorted(ani.loc[mask.fillna(False), "media_id"])


is_any = img_mask | aud_mask  # either-modality (Series, matches *_any doc)
SETS = {
    "zebra_img": ids(has_species(img_mask, "ZEBRA")),
    "elephant_aud": ids(has_species(aud_mask, "ELEPHANT")),
    "elephant_any": ids(has_species(is_any, "ELEPHANT")),
    "monkey_img": ids(has_species(img_mask, "MONKEY")),
    "monkey_aud": ids(has_species(aud_mask, "MONKEY")),
    "monkey_any": ids(has_species(is_any, "MONKEY")),
    "impala_img": ids(has_species(img_mask, "IMPALA")),
}
for species in ("elephant", "monkey"):
    union = SETS[f"{species}_any"]
    for branch, prefix in (("img", "img_"), ("aud", "aud_")):
        SETS[f"{species}_any__{branch}"] = [
            m for m in union if m.startswith(prefix)]
assert not {f"Q{i}.csv" for i in range(1, 11)} & {
    f"{n}.csv" for n in SETS}, "official-file collision"

for name, mine in SETS.items():
    path = GT / f"{name}.csv"
    cur = set(pd.read_csv(path, dtype=str).media_id) if path.exists() \
        else None
    if cur != set(mine):  # regenerate on drift, never from a run
        pd.DataFrame({"media_id": mine}).to_csv(path, index=False)
        print(f"REGENERATED {name}.csv ({len(mine)} rows)")
        cur = set(mine)
    ok = cur == set(mine)
    fails += not ok
    print(f"{'EQUAL' if ok else 'DIFF '} {name}: census {len(mine)}")

# ------------------------------------------- answer anchors vs officials
gt = {k: set(v) for k, v in SETS.items()}


def cities(q: str) -> set[str]:
    return set(ani[ani.media_id.isin(gt[q])].City)


def argmax_cities(q: str) -> set[str]:
    counts = ani[ani.media_id.isin(gt[q])].groupby("City").size()
    return set(counts[counts == counts.max()].index)


def argmax_pairs(q: str) -> set[tuple]:
    counts = ani[ani.media_id.isin(gt[q])].groupby(
        ["City", "StationID"]).size()
    return set(counts[counts == counts.max()].index)


def off_set(q: str, cols: list[str]) -> set:
    df = pd.read_csv(OFFICIAL / f"{q}.csv", dtype=str)
    return set(map(tuple, df[cols].dropna().itertuples(
        index=False, name=None)))


def off_count(q: str) -> int:
    return int(str(pd.read_csv(OFFICIAL / f"{q}.csv", dtype=str).iloc[0, 0]))


CHECKS = [
    ("Q1 count", len(gt["zebra_img"]), off_count("Q1")),
    ("Q2 count", len(gt["elephant_aud"]), off_count("Q2")),
    ("Q3 argmax", argmax_cities("zebra_img"),
     {c[0] for c in off_set("Q3", ["City"])}),
    ("Q4 argmax", argmax_cities("elephant_aud"),
     {c[0] for c in off_set("Q4", ["City"])}),
    ("Q5 union", cities("elephant_any"),
     {c[0] for c in off_set("Q5", ["City"])}),
    ("Q6 anti", cities("monkey_img") - cities("monkey_aud"),
     {c[0] for c in off_set("Q6", ["City"])}),
    ("Q7 co-occur", cities("zebra_img") & cities("impala_img"),
     {c[0] for c in off_set("Q7", ["City"])}),
    ("Q8 inter", cities("elephant_any") & cities("monkey_any"),
     {c[0] for c in off_set("Q8", ["City"])}),
    ("Q9 inter", cities("monkey_img") & cities("monkey_aud"),
     {c[0] for c in off_set("Q9", ["City"])}),
    ("Q10 argmax-pair", argmax_pairs("zebra_img"),
     off_set("Q10", ["City", "StationID"])),
]
for name, mine, official in CHECKS:
    ok = mine == official
    fails += not ok
    fmt = lambda v: v if isinstance(v, int) else sorted(v)  # noqa: E731
    print(f"{'EQUAL' if ok else 'DIFF '} {name}: census {fmt(mine)} | "
          f"official {fmt(official)}")

print(f"RESULT: {'ALL SELF-CHECKS EQUAL' if fails == 0 else f'{fails} FAILURES'}")
sys.exit(1 if fails else 0)
